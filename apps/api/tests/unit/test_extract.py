"""Extraction tests.

Design §4.1 pins one extractor per format, so this file is organised the same
way: one class per format, asserting the property that makes the format usable
for citations rather than merely "text came out".

Every test runs offline against in-memory bytes. The PDF is generated by
PyMuPDF itself, which keeps the suite honest about real PDF structure without
committing a binary fixture to the repository.
"""

from __future__ import annotations

import pytest
from app.ai.ingestion.extractors import (
    ExtractionError,
    extract,
    extractor_for,
    looks_like_scan,
)


def _pdf_bytes(pages: list[str]) -> bytes:
    """Build a real PDF with the given text on each page."""
    import pymupdf

    document = pymupdf.open()
    for text in pages:
        page = document.new_page()
        page.insert_text((72, 96), text, fontsize=12)
    data: bytes = document.tobytes()
    document.close()
    return data


class TestPdf:
    def test_pages_become_a_page_map(self):
        result = extract(
            _pdf_bytes(["Page one text.", "Page two text."]), "application/pdf", "a.pdf"
        )
        assert result.method == "pymupdf"
        assert result.page_count == 2
        assert [p for (_, _, p) in result.page_map] == [1, 2]

    def test_page_map_offsets_point_at_the_page_text(self):
        result = extract(_pdf_bytes(["Alpha marker", "Beta marker"]), "application/pdf", "a.pdf")
        for start, end, _page in result.page_map:
            assert result.text[start:end].strip(), "a page map entry must bracket real text"

    def test_text_is_normalized(self):
        result = extract(_pdf_bytes(["Lots    of   space"]), "application/pdf", "a.pdf")
        assert "Lots of space" in result.text

    def test_blank_pdf_reports_no_text_layer(self):
        """A scan is an explanation, not a spinner: code no_text_layer."""
        blank = _pdf_bytes([""])
        with pytest.raises(ExtractionError) as excinfo:
            extract(blank, "application/pdf", "scan.pdf")
        assert excinfo.value.code == "no_text_layer"
        assert "OCR" in excinfo.value.message


class TestMarkdown:
    def test_headings_survive_as_structure(self):
        """The chunker derives heading paths from `#` lines, so they must remain."""
        result = extract(
            b"# Deployment\n\nBody text.\n\n## Secrets\n\nMore.\n",
            "text/markdown",
            "notes.md",
        )
        assert result.method == "markdown-it"
        assert "# Deployment" in result.text
        assert "## Secrets" in result.text

    def test_emphasis_and_code_markers_are_stripped(self):
        result = extract(b"Some **bold** and `code` here.", "text/markdown", "n.md")
        assert "**" not in result.text
        assert "`" not in result.text
        assert "bold" in result.text and "code" in result.text

    def test_list_items_stay_separate_blocks(self):
        result = extract(b"Intro.\n\n- alpha\n- beta\n", "text/markdown", "n.md")
        assert "alpha" in result.text and "beta" in result.text
        assert "alpha beta" not in result.text, "list items must not be glued into one block"


class TestHtml:
    def test_boilerplate_is_dropped(self):
        """Nav and script text is not knowledge and must never become a citation."""
        html = (
            b"<html><body><nav>Home | About | Contact</nav>"
            b"<h1>Real title</h1><p>The actual content.</p>"
            b"<script>var tracking = 1;</script></body></html>"
        )
        result = extract(html, "text/html", "page.html")
        assert result.method == "beautifulsoup4"
        assert "Real title" in result.text
        assert "The actual content." in result.text
        assert "Contact" not in result.text
        assert "tracking" not in result.text

    def test_headings_produce_heading_markers(self):
        result = extract(b"<h1>Top</h1><p>Body.</p><h2>Sub</h2><p>More.</p>", "text/html", "p.html")
        assert "# Top" in result.text
        assert "## Sub" in result.text

    def test_nested_blocks_do_not_duplicate_text(self):
        result = extract(b"<div><p>Once only.</p></div>", "text/html", "p.html")
        assert result.text.count("Once only.") == 1

    def test_bare_text_node_still_works(self):
        result = extract(b"<html><body>just a string</body></html>", "text/html", "p.html")
        assert "just a string" in result.text


class TestTxt:
    def test_plain_text_passes_through(self):
        result = extract(b"line one\n\nline two", "text/plain", "a.txt")
        assert result.method == "plain"
        assert "line one" in result.text

    def test_utf8_bom_is_handled(self):
        result = extract(b"\xef\xbb\xbfhello", "text/plain", "a.txt")
        assert result.text.startswith("hello")

    def test_latin1_fallback_does_not_crash(self):
        result = extract(b"caf\xe9", "text/plain", "a.txt")
        assert "caf" in result.text


class TestDispatch:
    def test_extension_wins_over_a_wrong_mime_type(self):
        """Browsers send text/plain for unknown types; the name is the better hint."""
        extractor = extractor_for("text/plain", "report.html")
        assert extractor is not None
        assert extractor.__name__ == "extract_html"

    def test_unknown_type_is_refused_with_a_code(self):
        with pytest.raises(ExtractionError) as excinfo:
            extract(b"whatever", "application/zip", "a.zip")
        assert excinfo.value.code == "unsupported_file_type"

    def test_empty_bytes_are_refused(self):
        with pytest.raises(ExtractionError) as excinfo:
            extract(b"", "text/plain", "a.txt")
        assert excinfo.value.code == "empty_document"

    @pytest.mark.parametrize(
        ("mime", "name", "expected"),
        [
            ("application/pdf", "a.pdf", "extract_pdf"),
            ("text/markdown", "a.md", "extract_markdown"),
            ("text/html", "a.html", "extract_html"),
            ("text/plain", "a.txt", "extract_text"),
            (
                "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                "a.docx",
                "extract_docx",
            ),
        ],
    )
    def test_every_initial_format_has_an_extractor(self, mime, name, expected):
        extractor = extractor_for(mime, name)
        assert extractor is not None
        assert extractor.__name__ == expected


